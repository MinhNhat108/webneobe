export interface RaftSummaryItem {
  id: number;
  name: string;
  area_m2: number;
  perimeter_m: number;
  length_m: number;
  width_m: number;
  angle_deg: number;
  solarPanelCount?: number;
  focusFactor: number;
  cableCount: number;
  shoreAnchors: number;
  bedAnchors: number;
  selectedCable: string;
  waterDepth_m: number;
  bedAnchorDist_m: number;
  shoreAnchorDist_m: number;
  /**
   * Per-raft Broms pile overrides. Omit to keep the project-default pile
   * (shore D0.45/L6.5, bed D0.35/L8.0 — sized for the small/medium rafts).
   * The large rafts (higher line tension) need a bigger pile so BP-1..BP-5
   * clear their utilization <= 1.0 threshold; see .agentsroom memory
   * `features/mooring-calculation` for the Broms formula this feeds.
   */
  shorePileD_m?: number;
  shorePileL_m?: number;
  bedPileD_m?: number;
  bedPileL_m?: number;
  /** Bars on the tension face of the shore / lake-bed pile (one layer) and their diameter, mm. */
  shoreRebarFaceCount?: number;
  shoreRebarDia_mm?: number;
  bedRebarFaceCount?: number;
  bedRebarDia_mm?: number;
  /** ROUND shore pile: total bars of the cage, equally spaced on a circle. */
  shoreRebarCount?: number;
  /** Design strength of this raft's pile bars Rs, MPa (omit for the project value). */
  pileRebarRs_MPa?: number;
  /** Piles per shore / lake-bed anchor point (omit for 1). BÈ 5 uses twin piles. */
  shorePilesPerPoint?: number;
  bedPilesPerPoint?: number;
  /**
   * Huổi Vanh (2026-10-28, "Tính toán kiểu gì t thấy nhiều cọc đôi thế"): the lighter shore pile of a raft whose
   * own pile above has several piles per point. A shore point whose OWN line never pulls more than `tension_kN`
   * (largest tension of that line over every level and direction + pretension, as for the lake-bed bases) takes
   * this single pile; the lines in `heavyLines` keep the raft's pile. Written by buildRaftCatalogue.
   */
  shorePileLight?: ShorePileLight;
  /**
   * Hồ Bản Mòng: the raft's lines (bearing, span, pin level), its floating level
   * and its smallest gap to another raft — the input of the equilibrium
   * analysis that gives the line tension (src/lib/calc/mooringEquilibrium.ts).
   */
  mooringLayout?: import('../lib/calc/mooringEquilibrium').MooringLayoutInput;
  /** Hồ Bản Mòng: tie ropes joining this raft to a neighbour across a narrow gap (src/data/banMong/ties.json); counted in cableCount (C9). */
  ties?: number;
  /**
   * Hồ Bản Mòng: what happens when the storm lock of the level-compensating
   * devices does NOT engage — every line stays a constant-tension line of
   * `setTension_kN`, with `stroke_m` of margin each way, until the end stop
   * (mooringEquilibrium.ts, compensation 'device'). Written by buildRaftCatalogue.
   */
  lockFailure?: { setTension_kN: number; stroke_m: number; drift_m: number; maxTension_kN: number };
  /**
   * Huổi Vanh (lines re-tensioned every `line.adjustStep_m`): the same raft if the lines are cut once and never
   * re-tensioned — what the operating rule protects against (scripts/buildRaftCatalogue.ts).
   */
  noAdjust?: { drift_m: number; maxTension_kN: number };
}

export interface ShorePileLight {
  /** Design line tension of the light pile, kN. */
  tension_kN: number;
  shorePileL_m: number;
  shoreRebarCount: number;
  shoreRebarDia_mm: number;
  pileRebarRs_MPa: number;
  /** Shore lines pulling more than `tension_kN`: they keep the raft's (multi-)pile. */
  heavyLines: string[];
}

