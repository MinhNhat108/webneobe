/**
 * Hồ Bản Mòng (phường Chiềng Cơi, tỉnh Sơn La) — 8 raft clusters of the client
 * plan "191026-HOBANMONG - Floor Plan - BỐ TRÍ BÈ PIN PA2" (2026-10-19),
 * 92.624 m², 16.892 panels Trina TSM-740NEG21C.20 (740 Wp, 2384 × 1303 mm),
 * 12,5 MWp (Pre-FS).
 *
 * Same calculation basis as Huổi Vanh (the owner's settled option: bored D350
 * shore piles + RC bases with screw piles on the lake bed, default wind
 * 20 m/s); what differs is the lake:
 *  - levels MNC 649,50 / MNDB 662,76 / MNLKT 669,05 m — a 19,55 m range, more
 *    than three times the Huổi Vanh range;
 *  - the IFC terrain is in absolute elevations, and the design bed of each raft
 *    is the median IFC ground under it (647,0–649,2 m): design depth 13,6–15,8 m
 *    at MNDB. Under BÈ 5, 7 and 8 the ground is at or above MNC: those rafts
 *    sit on the bottom when the lake is drawn down.
 *
 * The catalogue rows (src/data/banMong/raftCatalogue.json) are generated by
 * `npx vite-node scripts/buildRaftCatalogue.ts -- --lake=ban-mong`.
 */
import raftCatalogue from './banMong/raftCatalogue.json';
import type { RaftSummaryItem, HUOI_VANH_PROJECT } from './huoiVanhProject';

export const BAN_MONG_RAFTS: RaftSummaryItem[] = raftCatalogue as RaftSummaryItem[];

/** Bản Mòng levels (m): the store, the engine and the schedules read them via src/data/lakes.ts. */
export const BAN_MONG_MNC_M = 649.5;
export const BAN_MONG_MNDB_M = 662.76;
export const BAN_MONG_MNLKT_M = 669.05;

/** The Bản Mòng project: the Huổi Vanh calculation basis with the lake, panels and documents of Bản Mòng. */
export function banMongProjectFrom(hv: typeof HUOI_VANH_PROJECT): typeof HUOI_VANH_PROJECT {
  const totalArea = BAN_MONG_RAFTS.reduce((s, r) => s + r.area_m2, 0);
  // Bản Mòng-only fields (MNC, the level compensation of the lines) are read by the engine through
  // EnvInput / LineInput; built apart so the Huổi Vanh object type stays the project type.
  const env = {
    ...hv.env,
    mnc_m: BAN_MONG_MNC_M,
    // the engine raises the high-water depth by mncn - mndbt (screw base uplift case)
    mndbt_m: BAN_MONG_MNDB_M,
    mncn_m: BAN_MONG_MNLKT_M,
    maxDepth_m: 16.0,
    waterDepth_m: 15.0
  };
  const line = {
    ...hv.line,
    // Deep water, 19.55 m level range. Default: CONTINUOUS compensation (adjustStep_m 0) — every
    // line is kept just taut at every level by a compensating device (hanging counterweight or
    // self-tensioning unit, NOT designed yet). What-ifs at 20 m/s (scripts/buildRaftCatalogue.ts):
    // fixed-cut cables: T up to 464 kN, no PES cable holds, drift up to 11 m;
    // re-tensioned every 2 m: up to 228 kN, bases up to 6.75 m (46 t); every 1 m: up to 198 kN;
    // continuous: 62–130 kN, PES-28…40, bases up to 5 m, drift under 1 m.
    levelCompensation: 'seasonal' as const,
    adjustStep_m: 0,
    eaPerMbl: 15
  };
  const note = `Tính toán hệ thống neo 8 cụm bè pin nổi hồ Bản Mòng (BÈ 1 … BÈ 8; tổng ${totalArea.toLocaleString('vi-VN')} m², 16.892 tấm pin 740 Wp), neo bờ bằng cọc khoan nhồi D350 và neo đáy bằng đế BTCT + 4 vít xoắn (cùng phương án đã chốt ở Huổi Vanh).`;
  return {
    ...hv,
    id: 'ban-mong-fpv',
    name: 'Dự án Điện Mặt Trời Nổi Hồ Bản Mòng',
    code: 'BM-FPV-2026',
    location: 'Hồ Bản Mòng, Phường Chiềng Cơi, Tỉnh Sơn La',
    date: '2026-10-19',
    note,
    meta: {
      ...hv.meta,
      name: 'Dự án Điện Mặt Trời Nổi Hồ Bản Mòng',
      code: 'BM-FPV-2026',
      location: 'Hồ Bản Mòng, Phường Chiềng Cơi, Tỉnh Sơn La',
      date: '2026-10-19',
      note: 'Hồ chứa nước Bản Mòng — Hệ neo 8 bè pin mặt trời nổi (neo bờ cọc khoan nhồi D350, neo đáy đế BTCT + vít xoắn)'
    },
    raft: {
      ...hv.raft,
      // Trina TSM-740NEG21C.20: 2,384 × 1,303 m
      solarPanelArea_m2: 3.106
    },
    env,
    line,
    attachments: [],
    raftsSummary: BAN_MONG_RAFTS
  };
}
